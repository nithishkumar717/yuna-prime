"""Paginated view composition.

This module provides a thin ``PaginatedView`` that combines a ``Paginator``
instance with navigation controls and a footer indicator. It **does not**
perform any pagination logic – all state lives in the ``Paginator``.
"""

from __future__ import annotations


from .paginator import Paginator
from .controls import (
    FirstControl,
    PreviousControl,
    NextControl,
    LastControl,
    PageSelectorControl,
    JumpToPageControl,
)


class PaginatedView:
    """Compose a paginator, its navigation controls, and a footer.

    Attributes
    ----------
    paginator: Paginator
        The paginator that owns the cursor and pages.
    controls: List[Any]
        Stateless control objects that know how to render themselves and call
        back into the paginator.
    """

    def __init__(self, paginator: Paginator):
        self.paginator = paginator
        # Build a default set of controls. The selector receives the list of
        # available page numbers.
        total_pages = paginator.total_pages()
        self.controls = [
            FirstControl(paginator),
            PreviousControl(paginator),
            NextControl(paginator),
            LastControl(paginator),
            PageSelectorControl(paginator, list(range(1, total_pages + 1))),
            JumpToPageControl(paginator),
        ]

    # ---------------------------------------------------------------------
    # Rendering helpers – each simply delegates to the current page and then
    # attaches control representations.
    # ---------------------------------------------------------------------
    def _render_footer(self) -> str:
        """Simple footer indicating the current page / total pages.
        """
        cur = self.paginator.cursor.page
        total = self.paginator.total_pages()
        return f"Page {cur} / {total}"

    def render_embed(self) -> dict:
        """Return a Discord‑style payload.

        The returned dict contains three keys:
        * ``content`` – the embed generated by the current page.
        * ``controls`` – a list of control representations for Discord.
        * ``footer`` – human‑readable page indicator.
        """
        page_embed = self.paginator.render_embed()
        controls = [c.render_embed() for c in self.controls]
        return {
            "content": page_embed,
            "controls": controls,
            "footer": self._render_footer(),
        }

    def render_html(self) -> str:
        """Compose an HTML representation of the page, controls and footer.
        """
        page_html = self.paginator.render_html()
        controls_html = "\n".join(c.render_html() for c in self.controls)
        footer_html = f"<div class='pagination-footer'>{self._render_footer()}</div>"
        return f"{page_html}\n{controls_html}\n{footer_html}"

    def render_text(self) -> str:
        """Plain‑text representation for CLI output.
        """
        page_text = self.paginator.render_text()
        controls_text = " ".join(c.render_text() for c in self.controls)
        footer_text = self._render_footer()
        return f"{page_text}\n{controls_text}\n{footer_text}"

    # ---------------------------------------------------------------------
    # Convenience helpers exposing paginator state.
    # ---------------------------------------------------------------------
    def total_pages(self) -> int:
        return self.paginator.total_pages()

    def current_page(self) -> int:
        return self.paginator.cursor.page

    def goto(self, page: int):
        self.paginator.goto(page)
        return self

__all__ = ["PaginatedView"]
